-- Учебная база «маркетплейс электроники» для уроков 2.6–2.11.
-- Загрузка: psql -d shop -f shop.sql   (базу создать заранее: createdb shop)

DROP TABLE IF EXISTS purchase, store_visit, product, customer, store CASCADE;

CREATE TABLE store (
    id      bigint PRIMARY KEY,
    name    varchar NOT NULL,
    rating  numeric(2,1) NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 5)
);

CREATE TABLE customer (
    id       bigint PRIMARY KEY,
    name     varchar NOT NULL,
    age      integer CHECK (age > 0),
    city     varchar,
    premium  boolean NOT NULL DEFAULT false
);

CREATE TABLE product (
    id        bigint PRIMARY KEY,
    store_id  bigint NOT NULL REFERENCES store(id),
    title     varchar NOT NULL,
    price     numeric(10,2) NOT NULL CHECK (price > 0),
    stock     integer NOT NULL DEFAULT 0 CHECK (stock >= 0)
);

CREATE TABLE store_visit (
    id           bigint PRIMARY KEY,
    customer_id  bigint NOT NULL REFERENCES customer(id),
    store_id     bigint NOT NULL REFERENCES store(id),
    visit_date   date NOT NULL
);

CREATE TABLE purchase (
    id             bigint PRIMARY KEY,
    customer_id    bigint NOT NULL REFERENCES customer(id),
    product_id     bigint NOT NULL REFERENCES product(id),
    purchase_date  date NOT NULL
);

